def save_template(name: str, content: str, template_type: str = "widget"):
    """Save generated code as template"""
    templates_dir = Path(__file__).parent / "samples" / "code_snippets"
    templates_dir.mkdir(parents=True, exist_ok=True)
    
    file_path = templates_dir / f"{template_type}_{name.lower()}.py"
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"Template saved: {file_path}")
    return file_path

