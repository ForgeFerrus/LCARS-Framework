    def generate_widget_class(self, class_name: str, base_class: str = "QWidget", 
                             era: str = "LCARS_25TH", components: List[Dict] = None) -> str:
        """Generate a complete widget class"""
        components = components or []
        
        imports = [
            "from PyQt6.QtWidgets import QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton",
            "from PyQt6.QtCore import Qt, pyqtSignal",
            "from PyQt6.QtGui import QFont",
            f"from lcars.themes.lcars_palette import LCARSEra, get_era_palette"
        ]
        
        code_lines = [
            '"""',
            f'Auto-generated LCARS {class_name}',
            'Generated by LCARS DevTools Code Generator',
            '"""',
            '',
            *imports,
            '',
            f'class {class_name}({base_class}):',
            '    """LCARS-styled widget"""',
            '    ',
            '    def __init__(self, parent=None):',
            '        super().__init__(parent)',
            f'        self.era_palette = get_era_palette(LCARSEra.{era})',
            '        self.setup_ui()',
            '        self.apply_lcars_style()',
            '    ',
            '    def setup_ui(self):',
            '        """Setup the user interface"""',
            '        self.main_layout = QVBoxLayout(self)',
            '        self.main_layout.setContentsMargins(10, 10, 10, 10)',
            '        ',
        ]
        
        # Add components
        for comp in components:
            comp_type = comp.get('type', 'QLabel')
            comp_name = comp.get('name', 'widget')
            comp_text = comp.get('text', '')
            
            code_lines.extend([
                f'        # {comp_name.replace("_", " ").title()}',
                f'        self.{comp_name} = {comp_type}("{comp_text}")',
                f'        self.main_layout.addWidget(self.{comp_name})',
                '        ',
            ])
        
        code_lines.extend([
            '    def apply_lcars_style(self):',
            '        """Apply LCARS styling"""',
            '        self.setStyleSheet(f"""',
            '            QWidget {{',
            '                background-color: {self.era_palette["background"]};',
            '                color: {self.era_palette["text"]};',
            '                font-family: "Courier New";',
            '            }}',
            '            QPushButton {{',
            '                background-color: {self.era_palette["button_colors"][0]};',
            '                color: {self.era_palette["background"]};',
            '                border: none;',
            '                border-radius: 12px;',
            '                padding: 10px;',
            '                font-weight: bold;',
            '            }}',
            '            QPushButton:hover {{',
            '                background-color: {self.era_palette["button_colors"][1]};',
            '            }}',
            '            QLabel {{',
            '                font-size: 14px;',
            '                padding: 5px;',
            '            }}',
            '        """)',
        ])
        
        return '\n'.join(code_lines)
    
